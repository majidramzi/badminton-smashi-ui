'use client';

import React from 'react';
import '../styles/smashi.css';

export type Tab = 'home' | 'calendar' | 'profile';
export type Training = {
  title: string;
  dateLabel: string;
  timeLabel: string;
  locationLabel?: string;
  groupCount: number;
  memberInitials?: string[];
};
export type Insight = { title: string; detail: string };
export type SmashiDashboardProps = {
  userName: string;
  /** Hour in the user's local timezone. Provide from application state. */
  localHour: number;
  nextTraining?: Training | null;
  completedSessions: number;
  weeklyGoal: number;
  insight?: Insight | null;
  recentSessionsSummary: string;
  friendsActivitySummary: string;
  logoSrc: string; // Approved logo file from Smashi; not generated by this kit
  iconBasePath?: string; // default: /smashi/icons
  activeTab?: Tab;
  unreadNotifications?: boolean;
  onDesignTraining: () => void;
  onUpcomingTraining: () => void;
  onInsights: () => void;
  onRecentSessions: () => void;
  onFriendsActivity: () => void;
  onNotifications: () => void;
  onNavigate: (tab: Tab) => void;
};

function getGreeting(hour: number) {
  return hour < 12 ? 'Good morning' : hour < 17 ? 'Good afternoon' : 'Good evening';
}
function Icon({name, base = '/smashi/icons', className = ''}: {name: string; base?: string; className?: string}) {
  return <span className={`sm-v2-icon ${className}`} aria-hidden="true">
    <picture>
      <source media="(hover: hover)" srcSet={`${base}/${name}_normal.svg`} />
      <img src={`${base}/${name}_normal.svg`} alt="" width={48} height={48} />
    </picture>
  </span>;
}
// The standalone _hover assets are available for native clients and hover/active state swaps.
// CSS changes tile intensity on hover; to swap actual files, use the native manifest or below NavIcon.
function NavIcon({name,base}:{name:string;base:string}) {
  return <span className="sm-v2-nav-icon" aria-hidden="true">
    <img className="sm-v2-icon-normal" src={`${base}/${name}_normal.svg`} alt="" />
    <img className="sm-v2-icon-hover" src={`${base}/${name}_hover.svg`} alt="" />
  </span>;
}
export default function SmashiDashboard(props: SmashiDashboardProps) {
  const base = props.iconBasePath ?? '/smashi/icons';
  const pct = props.weeklyGoal > 0 ? Math.min(100, Math.max(0, 100 * props.completedSessions / props.weeklyGoal)) : 0;
  const t = props.nextTraining;
  const left = Math.max(0, props.weeklyGoal - props.completedSessions);
  const nav: {key:Tab;label:string}[] = [{key:'home',label:'Home'},{key:'calendar',label:'Calendar'},{key:'profile',label:'Profile'}];
  return <main className="sm-v2-root">
    <div className="sm-v2-shell">
      <header className="sm-v2-header">
        <img src={props.logoSrc} alt="Smashi" className="sm-v2-logo" />
        <button className="sm-v2-notification" onClick={props.onNotifications} aria-label="Notifications">
          <NavIcon name="notification" base={base}/>{props.unreadNotifications && <span className="sm-v2-unread"/>}
        </button>
      </header>
      <section className="sm-v2-welcome">
        <h1>{getGreeting(props.localHour)}, <span>{props.userName}!</span></h1>
        <p>I am here to help you build today's training.</p>
      </section>
      <div className="sm-v2-stack">
        <button className="sm-v2-card sm-v2-cta" onClick={props.onDesignTraining}>
          <NavIcon name="design-training" base={base}/>
          <span className="sm-v2-cta-content"><strong>Design a Training</strong><small>Create a personalized badminton session with AI.</small></span>
          <span className="sm-v2-arrow"><img src={`${base}/arrow-right_normal.svg`} alt="" /></span>
        </button>
        <button className="sm-v2-card sm-v2-training" onClick={props.onUpcomingTraining} aria-label="View upcoming training and group">
          <div className="sm-v2-training-main">
            <div className="sm-v2-eyebrow"><img src={`${base}/upcoming-training_normal.svg`} alt="" />Upcoming Training</div>
            <strong>{t?.title ?? 'No upcoming training'}</strong>
            <small>{t ? [t.dateLabel,t.timeLabel,t.locationLabel].filter(Boolean).join(' · ') : 'Schedule your next session'}</small>
          </div>
          <div className="sm-v2-training-group">
            <div className="sm-v2-eyebrow"><img src={`${base}/group_normal.svg`} alt="" />Group ({t?.groupCount ?? 0})</div>
            <div className="sm-v2-avatars">{(t?.memberInitials ?? []).slice(0,3).map((x,i)=><span key={i} className="sm-v2-avatar">{x}</span>)}</div>
            <small>{t ? `You + ${Math.max(0,t.groupCount-1)} guests` : 'No group yet'}</small>
          </div>
        </button>
        <section className="sm-v2-card sm-v2-progress" aria-label="Weekly progress">
          <div className="sm-v2-progress-head"><h2>Weekly Progress</h2><span>{props.completedSessions} of {props.weeklyGoal} sessions</span></div>
          <div className="sm-v2-track" role="progressbar" aria-label="Weekly sessions completed" aria-valuemin={0} aria-valuemax={props.weeklyGoal || 1} aria-valuenow={Math.min(props.completedSessions,props.weeklyGoal || 1)}><div className="sm-v2-fill" style={{width:`${pct}%`}} /></div>
          <p>{left === 0 ? 'Weekly goal reached!' : `${left} session${left===1?'':'s'} left to hit your weekly goal.`}</p>
        </section>
        {props.insight && <button className="sm-v2-card sm-v2-list sm-v2-insight" onClick={props.onInsights}>
          <NavIcon name="ai-insights" base={base}/><span className="sm-v2-list-body"><strong>AI Insights</strong><small>{props.insight.title}<br/>{props.insight.detail}</small></span><span className="sm-v2-chevron">›</span>
        </button>}
        <button className="sm-v2-card sm-v2-list" onClick={props.onRecentSessions}>
          <NavIcon name="recent-sessions" base={base}/><span className="sm-v2-list-body"><strong>Recent Sessions</strong><small>{props.recentSessionsSummary}</small></span><span className="sm-v2-chevron">›</span>
        </button>
        <button className="sm-v2-card sm-v2-list" onClick={props.onFriendsActivity}>
          <NavIcon name="friends-activity" base={base}/><span className="sm-v2-list-body"><strong>Friends Activity</strong><small>{props.friendsActivitySummary}</small></span><span className="sm-v2-pill">Group</span><span className="sm-v2-chevron">›</span>
        </button>
      </div>
    </div>
    <nav className="sm-v2-dock" aria-label="Main navigation">
      {nav.map(item=><button key={item.key} onClick={()=>props.onNavigate(item.key)} aria-current={(props.activeTab??'home')===item.key?'page':undefined}>
        <NavIcon name={item.key} base={base}/><span>{item.label}</span>
      </button>)}
    </nav>
  </main>;
}
